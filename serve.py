"""Local dev server for the birthday site.

Usage:
    python serve.py            # serves on http://127.0.0.1:5173
    python serve.py 8080       # custom port

On start it scans ./photos (any casing) and writes photo-manifest.js, which maps
  * photo1..photo8 -> real image files (.png/.jpg/.jpeg/.webp/.gif/.avif, any case,
    names like "Photo_3.JPG" or "photo-3.jpeg")
  * video1..video3 -> real video files (.mp4/.webm/.mov/.m4v); if they aren't named
    videoN, any other video files in the folder are used in alphabetical order.
The server supports HTTP Range requests so <video> can stream, seek and loop.
Stop with Ctrl+C.
"""
import http.server
import json
import os
import re
import shutil
import socket
import sys
from functools import partial
from pathlib import Path

ROOT = Path(__file__).resolve().parent
IMG_EXTS = [".jpg", ".jpeg", ".png", ".webp", ".avif", ".gif"]
VID_EXTS = [".mp4", ".webm", ".m4v", ".mov"]
PHOTO_RE = re.compile(r"^photo[\s_-]*0*(\d+)$", re.IGNORECASE)
VIDEO_RE = re.compile(r"^video[\s_-]*0*(\d+)$", re.IGNORECASE)
VIDEO_SLOTS = 3   # page 5 shows video1..video3


def _scan(folder: Path, exts: list, pattern: re.Pattern, count: int) -> dict:
    found: dict[int, Path] = {}
    for f in sorted(folder.iterdir()):
        if not f.is_file() or f.suffix.lower() not in exts or f.stat().st_size == 0:
            continue
        m = pattern.match(f.stem)
        if not m or not 1 <= int(m.group(1)) <= count:
            continue
        n = int(m.group(1))
        prev = found.get(n)
        if prev is None or exts.index(f.suffix.lower()) < exts.index(prev.suffix.lower()):
            found[n] = f
    return found


def build_manifest() -> None:
    photo_dirs = [p for p in ROOT.iterdir() if p.is_dir() and p.name.lower() == "photos"]
    photos: dict[int, Path] = {}
    videos: dict[int, Path] = {}
    if photo_dirs:
        folder = photo_dirs[0]
        photos = _scan(folder, IMG_EXTS, PHOTO_RE, 8)
        videos = _scan(folder, VID_EXTS, VIDEO_RE, VIDEO_SLOTS)
        # Fallback: fill missing video slots with any other video files.
        spare = [f for f in sorted(folder.iterdir())
                 if f.is_file() and f.suffix.lower() in VID_EXTS and f not in videos.values()]
        for n in range(1, VIDEO_SLOTS + 1):
            if n not in videos and spare:
                videos[n] = spare.pop(0)

    rel = lambda p: p.relative_to(ROOT).as_posix()
    photo_map = {str(n): rel(photos[n]) for n in sorted(photos)}
    video_map = {str(n): rel(videos[n]) for n in sorted(videos)}
    (ROOT / "photo-manifest.js").write_text(
        "// Auto-generated by serve.py - maps photo/video numbers to real files.\n"
        f"window.PHOTO_MANIFEST = {json.dumps(photo_map, indent=2)};\n"
        f"window.VIDEO_MANIFEST = {json.dumps(video_map, indent=2)};\n"
        "window.MEDIA_MANIFEST_OK = true;  // lists are authoritative: missing slots get a placeholder, no probing\n",
        encoding="utf-8",
    )
    for n in range(1, 9):
        print(f"  photo{n}: {photo_map.get(str(n), 'MISSING (placeholder will be shown)')}")
    for n in range(1, VIDEO_SLOTS + 1):
        print(f"  video{n}: {video_map.get(str(n), 'MISSING (placeholder will be shown)')}")


class Handler(http.server.SimpleHTTPRequestHandler):
    extensions_map = {
        **http.server.SimpleHTTPRequestHandler.extensions_map,
        ".mp4": "video/mp4", ".m4v": "video/mp4", ".webm": "video/webm", ".mov": "video/quicktime",
        ".js": "text/javascript", ".css": "text/css", ".svg": "image/svg+xml",
    }
    _range_len = None

    def do_GET(self):
        if self.path == "/favicon.ico":  # page uses an inline SVG icon
            self.send_response(204)
            self.end_headers()
            return
        super().do_GET()

    def send_head(self):
        """Adds single-range 'Range: bytes=a-b' support (206 Partial Content)."""
        self._range_len = None
        rng = self.headers.get("Range")
        path = self.translate_path(self.path)
        if not rng or os.path.isdir(path):
            return super().send_head()
        m = re.fullmatch(r"bytes=(\d*)-(\d*)", rng.strip())
        if not m or m.groups() == ("", ""):
            return super().send_head()
        try:
            f = open(path, "rb")
        except OSError:
            self.send_error(404, "File not found")
            return None
        size = os.fstat(f.fileno()).st_size
        a, b = m.groups()
        if a == "":
            start, end = max(0, size - int(b)), size - 1
        else:
            start, end = int(a), (int(b) if b else size - 1)
        end = min(end, size - 1)
        if start >= size or start > end:
            f.close()
            self.send_response(416)
            self.send_header("Content-Range", f"bytes */{size}")
            self.end_headers()
            return None
        self.send_response(206)
        self.send_header("Content-Type", self.guess_type(path))
        self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.send_header("Content-Length", str(end - start + 1))
        self.end_headers()
        f.seek(start)
        self._range_len = end - start + 1
        return f

    def copyfile(self, source, outputfile):
        try:
            if self._range_len is None:
                shutil.copyfileobj(source, outputfile)
                return
            left = self._range_len
            while left > 0:
                chunk = source.read(min(64 * 1024, left))
                if not chunk:
                    break
                outputfile.write(chunk)
                left -= len(chunk)
        except (ConnectionResetError, BrokenPipeError, ConnectionAbortedError):
            pass  # browser cancelled a media request - normal for <video>

    def end_headers(self):
        self.send_header("Cache-Control", "no-store")
        self.send_header("Accept-Ranges", "bytes")
        super().end_headers()

    def log_message(self, fmt, *args):
        if args and str(args[1]).startswith(("4", "5")):
            super().log_message(fmt, *args)


class Server(http.server.ThreadingHTTPServer):
    """Claims the port exclusively. On Windows, SO_REUSEADDR (Python's default here) lets
    several servers silently share one port and the oldest one keeps answering."""
    allow_reuse_address = os.name != "nt"

    def server_bind(self):
        if os.name == "nt" and hasattr(socket, "SO_EXCLUSIVEADDRUSE"):
            self.socket.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
        super().server_bind()


def main():
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 5173
    print("Media mapping:")
    build_manifest()
    handler = partial(Handler, directory=str(ROOT))
    try:
        httpd = Server(("127.0.0.1", port), handler)
    except OSError:
        print(f"\nPort {port} is already in use - is another copy of serve.py still running?\n"
              f"Stop it (Ctrl+C in its terminal) or pick another port: python serve.py {port + 1}")
        sys.exit(1)
    with httpd:
        print(f"\nBirthday site running at http://127.0.0.1:{port}/  (Ctrl+C to stop)", flush=True)
        try:
            httpd.serve_forever()
        except KeyboardInterrupt:
            print("\nStopped.")


if __name__ == "__main__":
    main()
